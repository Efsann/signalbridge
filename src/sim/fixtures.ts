/**
 * Returns a deterministic or randomly chosen fixture template for a category and language.
 */
export function getFixtureTemplate(
  category: CategoryId,
  language: "az" | "ru" | "en" | "mixed",
  index?: number
): ComplaintTemplate {
  const list = FIXTURE_TEMPLATES[category]?.[language] || FIXTURE_TEMPLATES.other_unclear.az;
  const idx =
    index !== undefined ? Math.abs(index) % list.length : Math.floor(Math.random() * list.length);
  return list[idx];
}

