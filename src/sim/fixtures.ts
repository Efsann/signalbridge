/**
 * Returns candidate change log entries from the 6 hours before firstComplaintAt.
 * (Does not pre-filter by district).
 */
export function getCandidateChangesBefore(
  firstComplaintAt: number,
  changeLog: ChangeEntry[] = FIXTURE_CHANGE_LOG
): ChangeEntry[] {
  const sixHoursMs = 6 * 60 * 60 * 1000;
  const cutoffTime = firstComplaintAt - sixHoursMs;

  return changeLog.filter(
    (entry) => entry.ts >= cutoffTime && entry.ts <= firstComplaintAt
  );
}

